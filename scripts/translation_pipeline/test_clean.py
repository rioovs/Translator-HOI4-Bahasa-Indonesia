    m = re.match(r'^(\s*[a-zA-Z0-9_]+:\s*(?:[0-9]+\s*)?\")(.*)(\"\s*(?:#.*)?)$', line_clean)
    if m:
        prefix = m.group(1)
        old_val = m.group(2)
        suffix = m.group(3)
        key = prefix.strip().split(':')[0].strip()
        if key in all_trans:
            trans_val = all_trans[key]
            # Escape literal quotes
            escaped_val = re.sub(r'(?<!\\)"', r'\"', trans_val)
            new_line = f"{prefix}{escaped_val}{suffix}\n"
            new_lines.append(new_line)
            replaced_keys.add(key)
            continue

    # If it was an empty line generated by the extra newline bug, skip it if following a replaced key?
