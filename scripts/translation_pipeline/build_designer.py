def translate_designer():
    src = r'F:\Apps\Hearts_of_Iron_IV\Hearts of Iron IV\localisation\english\designer_l_english.yml'
    with open(src, 'r', encoding='utf-8-sig', errors='ignore') as f:
        lines = f.readlines()

    out_lines = ['l_braz_por:\n']
    missing = []
    translated_count = 0

    for idx, line in enumerate(lines[1:], 2):
        raw = line.rstrip('\r\n')
        stripped = raw.strip()
        if not stripped or stripped.startswith('#'):
            out_lines.append(raw + '\n')
            continue
        m = re.match(r'^(\s*)([a-zA-Z0-9_.\-]+):(\d*)\s*"(.*)"\s*$', raw)
        if m:
            indent, key, version, val = m.groups()
            v_suffix = f":{version}" if version != "" else ":"
            # check translation
            trans_val = TRANSLATIONS.get(key)
            if trans_val is None:
                # also check key:version
                trans_val = TRANSLATIONS.get(f"{key}:{version}")
            if trans_val is not None:
                translated_count += 1
                out_lines.append(f'{indent}{key}{v_suffix} "{trans_val}"\n')
            else:
                missing.append((key, val))
                out_lines.append(f'{indent}{key}{v_suffix} "{val}"\n')
        else:
            out_lines.append(raw + '\n')

    print(f'Designer: {translated_count} translated, {len(missing)} missing')
    if missing:
        print('Missing sample:', missing[:5])
    return ''.join(out_lines)

